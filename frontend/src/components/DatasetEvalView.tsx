import { useEffect, useState } from 'react'
import { api, type Json } from '../api'
import { Card, Empty, KV, Table, ZoomImage } from './ui'

type R = Record<string, any>

export function DatasetEvalView() {
  const [data, setData] = useState<R | null>(null)
  const [err, setErr] = useState<string | null>(null)
  useEffect(() => { api.datasetEvaluation().then((d: Json) => setData(d as R)).catch((e) => setErr(String(e.message ?? e))) }, [])
  if (err) return <Empty>{err}</Empty>
  if (!data) return <Empty>Loading dataset evaluation…</Empty>
  const ves = data.vessels?.methods ?? {}
  const disc = data.disc_localization ?? {}
  const les = data.lesions_image_level ?? {}
  const dr = data.dr_flag ?? {}
  return (
    <div className="space-y-5">
      <Card title="STARE — dataset-level evaluation"
        subtitle={`Generated by scripts/evaluate_stare.py. Tuning split ${data.split?.tuning}, held-out split ${data.split?.held_out}.`}>
        <p className="text-[13px] text-ink-soft">Every number below was computed from the downloaded STARE annotations. Parameters
          were chosen on the tuning split (lesions, screening) or by comparing three classical methods on all 20 vessel images
          (no separate vessel test set exists — a stated limitation).</p>
      </Card>

      <Card title="Vessel segmentation (20 images, reference: observer AH)" subtitle={data.vessels?.protocol}>
        <div className="space-y-5">
          <Table rows={Object.entries(ves).map(([m, v]) => ({ method: m, ...(v as R) }))} columns={[
            { key: 'method', label: 'Method' },
            ...['sensitivity', 'specificity', 'precision', 'f1', 'iou', 'roc_auc'].map((k) => ({ key: k, label: k, align: 'right' as const }))]} />
          {(data.charts ?? []).map((c: string) => <div key={c} className="max-w-3xl"><ZoomImage src={c} title="Vessel method comparison" light /></div>)}
        </div>
      </Card>

      <Card title="Optic-disc localisation" subtitle={disc.criterion}>
        <Table rows={[
          { set: 'Hoover & Goldbaum 81-image set — ours', ...disc.hoover_81_image_set },
          { set: 'Hoover & Goldbaum 81-image set — published result', ...(disc.published_baseline_81_set ?? {}) },
          { set: 'All images with visible nerve — ours', ...disc.all_visible_nerve_images },
        ]} columns={[{ key: 'set', label: 'Image set / method' }, { key: 'n', label: 'n', align: 'right' },
          { key: 'success_rate', label: 'Success rate', align: 'right' }, { key: 'median_distance_px', label: 'Median dist. (px)', align: 'right' },
          { key: 'disc_segmented_rate', label: 'Disc segmented', align: 'right' }]} />
      </Card>

      <Card title="DR lesion candidates vs STARE image-level manifestation grades"
        subtitle="Presence = grade ≥ 2; unknown grades excluded. Count threshold chosen by Youden index on the tuning split only.">
        <Table rows={Object.entries(les).flatMap(([k, v]: [string, any]) => ['tuning', 'held_out'].filter((s) => v[s]).map((s) => ({
          category: k, split: s, n: v[s].n, positives: v[s].positives, auc: v[s].auc_of_candidate_count,
          threshold: `count ≥ ${v.count_threshold_from_tuning}`, sens: v[s].at_threshold.sensitivity, spec: v[s].at_threshold.specificity,
        })))} columns={[{ key: 'category', label: 'Category' }, { key: 'split', label: 'Split' }, { key: 'n', label: 'n', align: 'right' },
          { key: 'positives', label: 'Positives', align: 'right' }, { key: 'auc', label: 'AUC (count)', align: 'right' },
          { key: 'threshold', label: 'Threshold' }, { key: 'sens', label: 'Sensitivity', align: 'right' }, { key: 'spec', label: 'Specificity', align: 'right' }]} />
      </Card>

      <Card title="Experimental DR flag vs diagnosis" subtitle={dr.reference}>
        <div className="grid gap-5 lg:grid-cols-2">
          <Table rows={['tuning', 'held_out'].filter((s) => dr[s]).map((s) => ({ split: s, ...dr[s] }))} columns={[
            { key: 'split', label: 'Split' }, ...['n', 'TP', 'FP', 'FN', 'TN', 'sensitivity', 'specificity', 'precision']
              .map((k) => ({ key: k, label: k, align: 'right' as const }))]} />
          <div><div className="mb-1 text-[12px] font-semibold">Rule</div>
            {(dr.rule ?? []).map((c: R, i: number) => <div key={i} className="font-mono text-[12px]">{c.feature} {c.op} {c.threshold}</div>)}
            <p className="mt-1 text-[12px] text-ink-faint">At least 2 of the 3 conditions. See README for how the rule was chosen.</p></div>
        </div>
      </Card>

      <Card title="Glaucoma / CDR"><KV data={data.vcdr_distribution ?? {}} /></Card>
    </div>
  )
}
